#!/usr/bin/env bash
# M10 A (docs/parity/m10.md, "E2E in CI"): writes the per-run env file for one
# e2e suite. Every secret is fresh `openssl rand -hex 32` output for a
# throwaway run against loopback services; nothing is echoed, and the file
# lives under the gitignored .secrets/ (never uploaded as an artifact).
#
#   scripts/e2e/ci-env.sh <core|m6|m8|m9|m9-prod> [output]
#
# Default output: $E2E_CI_ENV_FILE or .secrets/ci.env. Load it with
# scripts/e2e/with-env.sh <command>.
set -euo pipefail

suite="${1:?usage: ci-env.sh <core|m6|m8|m9|m9-prod> [output]}"
out="${2:-${E2E_CI_ENV_FILE:-.secrets/ci.env}}"

case "$suite" in
  core|m6|m8|m9|m9-prod) ;;
  *) echo "ci-env.sh: unknown suite '$suite'" >&2; exit 2 ;;
esac

rand() { openssl rand -hex 32; }

mkdir -p "$(dirname "$out")"
umask 077

app_url="http://localhost:3000"
fake_url="http://127.0.0.1:4010"
node_env="development"
[ "$suite" = "m9-prod" ] && node_env="production"

{
  echo "# Generated by scripts/e2e/ci-env.sh ($suite). Throwaway per-run test values; never commit or upload."
  echo "E2E_SUITE=$suite"
  echo "NODE_ENV=$node_env"
  echo "NEXT_TELEMETRY_DISABLED=1"
  echo "NEXT_PUBLIC_APP_URL=$app_url"
  echo "E2E_BASE_URL=$app_url"
  echo "MEETSUM_STORAGE=postgres"
  echo "DATABASE_URL=postgresql://meetings:meetings@127.0.0.1:5432/meetsum_e2e"
  echo "REDIS_URL=redis://127.0.0.1:6379"
  echo "S3_ENDPOINT=http://127.0.0.1:9000"
  echo "S3_REGION=us-east-1"
  echo "S3_BUCKET=meetsum-media"
  echo "S3_FORCE_PATH_STYLE=true"
  echo "S3_ACCESS_KEY=e2e$(openssl rand -hex 8)"
  echo "S3_SECRET_KEY=$(rand)"
  echo "MEETSUM_SESSION_SECRET=$(rand)"
  echo "WEBHOOK_SIGNING_SECRET=$(rand)"
  echo "GOOGLE_OAUTH_TOKEN_ENCRYPTION_KEY=$(rand)"
  # No Google, Teams or retention background work in CI.
  echo "MEETSUM_SCHEDULE_GOOGLE_SYNC=false"
  echo "MEETSUM_EMBEDDING_PROVIDER=hash"
  echo "MEETSUM_INDEX_DEBOUNCE_MS=1000"
  echo "MEETSUM_QUEUE_ENQUEUE_TIMEOUT_MS=3000"
  echo "MEETSUM_WORKER_HEALTH_PORT=3101"
  echo "MEETSUM_WORKER_HEALTH_HOST=127.0.0.1"
  echo "LOG_LEVEL=info"

  if [ "$suite" != "m9-prod" ]; then
    # Fakes and replay: development only (refused in production).
    echo "MEETSUM_INTEGRATIONS_FAKE_BASE_URL=$fake_url"
    echo "E2E_FAKE_BASE_URL=$fake_url"
    echo "LOCAL_TRANSCRIPTION_URL=$fake_url/asr"
    echo "LOCAL_TRANSCRIPTION_SEND_HOTWORDS=false"
    echo "MEETSUM_ASR_CHAIN=local-whisper-chunked"
    echo "MEETSUM_LLM_REPLAY_DIR=tests/fixtures/e2e/llm-replay"
    echo "MEETSUM_LLM_REPLAY_DELAY_MS=20"
  fi

  case "$suite" in
    core)
      echo "MEETSUM_BOT_ENABLED=true"
      echo "VEXA_API_URL=http://127.0.0.1:18056"
      echo "VEXA_API_KEY=$(rand)"
      echo "VEXA_WEBHOOK_SECRET=$(rand)"
      echo "E2E_FAKE_VEXA_PORT=18056"
      ;;
    m8)
      echo "MEETSUM_OAUTH_REDIRECT_BASE=$app_url"
      echo "MEETSUM_WEBHOOK_ALLOWED_HOSTS=127.0.0.1"
      echo "MEETSUM_MS_CALENDAR_SYNC_MINUTES=1"
      echo "MEETSUM_EMAIL_PROVIDER=log"
      echo "E2E_EMAIL_CAPTURE_FILE=.secrets/e2e-emails.jsonl"
      for provider in SLACK NOTION HUBSPOT MS AZURE GOOGLE_OAUTH GOOGLE; do
        echo "${provider}_CLIENT_ID=fake-$(echo "$provider" | tr '[:upper:]_' '[:lower:]-')"
        echo "${provider}_CLIENT_SECRET=$(rand)"
      done
      ;;
  esac
} > "$out"

chmod 600 "$out"

# The S3 server's identity file (SeaweedFS `-s3.config`), next to the env file.
s3_access="$(grep '^S3_ACCESS_KEY=' "$out" | cut -d= -f2-)"
s3_secret="$(grep '^S3_SECRET_KEY=' "$out" | cut -d= -f2-)"
s3_config="$(dirname "$out")/s3.json"
printf '{"identities":[{"name":"e2e","credentials":[{"accessKey":"%s","secretKey":"%s"}],"actions":["Admin","Read","Write","List","Tagging"]}]}\n' \
  "$s3_access" "$s3_secret" > "$s3_config"
# The container reads it as another user.
chmod 644 "$s3_config"

echo "ci-env.sh: wrote the $suite env file ($(grep -c '=' "$out") variables) to $out"
