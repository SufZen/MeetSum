/**
 * M10 core-flow and bot e2e seed (docs/parity/m10.md, A3/A4).
 *
 *   npm run m10:e2e-seed
 *
 * Needs DATABASE_URL (migrated) on localhost and MEETSUM_SESSION_SECRET (the
 * app's). Refuses any non-local database or base URL. Seeds, with ids
 * prefixed `e2e_m10_` (re-running replaces them; their meetings cascade):
 * - W1 (60 days old, so no onboarding redirect) with an owner and a member,
 *   Hebrew workspace defaults: locale `he`, Hebrew summaries, the
 *   `hebrew_business` template (the structured replay recordings are written
 *   for it), public sharing on, optional AI features off;
 * - W2 with its own owner (must never see W1's meetings).
 * No meetings: the core spec uploads tests/fixtures/e2e/media/he-en-30s.wav.
 * Session cookies and ids go to E2E_M10_ENV_FILE (then E2E_ENV_FILE, default
 * `.secrets/e2e-m10.env`, gitignored), never to stdout.
 */
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"

import { createSessionCookie, getSessionSecret } from "@/lib/auth/session"
import { getDatabasePool, type Queryable } from "@/lib/db/client"
import { suiteEnvFile } from "@/scripts/e2e/env-file"
import { assertLocal } from "@/scripts/e2e/local-guard"

const PREFIX = "e2e_m10_"
const W1 = `${PREFIX}ws_1`
const W2 = `${PREFIX}ws_2`
const DAY = 86_400_000

export const M10_USERS = {
  owner: { id: `${PREFIX}owner`, email: "m10-owner@example.test", name: "דנה כהן", workspace: W1, role: "owner" },
  member: { id: `${PREFIX}member`, email: "m10-member@example.test", name: "Noa Levi", workspace: W1, role: "member" },
  w2: { id: `${PREFIX}w2_owner`, email: "m10-w2-owner@example.test", name: "W2 Owner", workspace: W2, role: "owner" },
} as const

/** W1 workspace settings (lib/settings/app-settings.ts keys). */
export const M10_W1_SETTINGS: Record<string, unknown> = {
  defaultLocale: "he",
  summaryTemplate: "hebrew_business",
  summaryLanguageMode: "he",
  publicSharingEnabled: true,
  defaultMeetingVisibility: "workspace",
  autoTitleMode: "off",
  aiFeatures: { sentiment: false, prepBriefs: false },
}

export function assertLocalSeedTarget(env: NodeJS.ProcessEnv = process.env): void {
  if (!env.DATABASE_URL) throw new Error("DATABASE_URL is required")
  assertLocal(env.DATABASE_URL, "DATABASE_URL")
  if (env.E2E_BASE_URL) assertLocal(env.E2E_BASE_URL, "E2E_BASE_URL")
}

/** Seeds `db` and returns the env-file lines. Exported for tests. */
export async function seedM10E2E(db: Queryable, options: { secret: string; now?: number }): Promise<string[]> {
  const q = (text: string, values?: unknown[]) => db.query(text, values)
  const now = options.now ?? Date.now()
  const iso = (ms: number) => new Date(ms).toISOString()

  await q("delete from meetings where workspace_id like 'e2e\\_m10\\_%'")
  await q("delete from memberships where workspace_id like 'e2e\\_m10\\_%'")
  await q("update users set default_workspace_id = null where id like 'e2e\\_m10\\_%'")
  await q("delete from workspace_settings where workspace_id like 'e2e\\_m10\\_%'")
  await q("delete from workspaces where id like 'e2e\\_m10\\_%'")

  for (const user of Object.values(M10_USERS)) {
    await q(
      `insert into users (id, email, name, locale) values ($1, $2, $3, 'he')
       on conflict (id) do update set name = excluded.name, locale = 'he', preferences = '{}'::jsonb`,
      [user.id, user.email, user.name]
    )
  }
  for (const [id, name] of [
    [W1, "Acme ישראל"],
    [W2, "Other Co"],
  ] as const) {
    await q("insert into workspaces (id, name, slug, created_at) values ($1, $2, $1, $3)", [id, name, iso(now - 60 * DAY)])
  }
  for (const user of Object.values(M10_USERS)) {
    await q("insert into memberships (workspace_id, user_id, role) values ($1, $2, $3)", [user.workspace, user.id, user.role])
    await q("update users set default_workspace_id = $2 where id = $1", [user.id, user.workspace])
  }
  for (const [key, value] of Object.entries(M10_W1_SETTINGS)) {
    await q("insert into workspace_settings (workspace_id, key, value) values ($1, $2, $3::jsonb)", [W1, key, JSON.stringify(value)])
  }

  const cookie = (user: (typeof M10_USERS)[keyof typeof M10_USERS]) =>
    createSessionCookie({ userId: user.id, email: user.email, name: user.name }, { secret: options.secret }).value

  return [
    "# Generated by npm run m10:e2e-seed. Test-only session cookies; do not commit.",
    `E2E_M10_OWNER_SESSION=${cookie(M10_USERS.owner)}`,
    `E2E_M10_MEMBER_SESSION=${cookie(M10_USERS.member)}`,
    `E2E_M10_W2_SESSION=${cookie(M10_USERS.w2)}`,
    `E2E_M10_W1_WORKSPACE_ID=${W1}`,
    `E2E_M10_W2_WORKSPACE_ID=${W2}`,
  ]
}

async function main() {
  assertLocalSeedTarget()

  const pool = getDatabasePool()
  const lines = await seedM10E2E(pool, { secret: getSessionSecret() })
  const file = suiteEnvFile("m10")

  await mkdir(path.dirname(path.resolve(file)), { recursive: true })
  await writeFile(file, `${lines.join("\n")}\n`, { mode: 0o600 })
  console.log(`Seeded the M10 fixture (2 workspaces, ${Object.keys(M10_USERS).length} users).`)
  console.log(`Test credentials written to ${file}.`)
  await pool.end()
}

if (process.argv[1] && /m10-e2e-seed/.test(process.argv[1])) {
  main().catch(async (error: unknown) => {
    console.error(error instanceof Error ? error.message : "Seed failed")
    await getDatabasePool().end().catch(() => undefined)
    process.exit(1)
  })
}
