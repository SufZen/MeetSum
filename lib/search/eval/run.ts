/**
 * Eval runner and report (docs/parity/m6.md, B8). The report holds metrics,
 * the corpus hash and the commit, never transcript or query text.
 */
import { EVAL_CATEGORIES, type EvalCorpus } from "@/lib/search/eval/corpus"
import type { EvalEngine } from "@/lib/search/eval/engines"
import { firstRelevantRank, metricsByCategory, type Metrics, type QueryResult } from "@/lib/search/eval/metrics"

export type EngineReport = { engine: EvalEngine["name"]; results: QueryResult[]; metrics: Record<string, Metrics> }

export async function runEngine(corpus: EvalCorpus, engine: EvalEngine): Promise<EngineReport> {
  const results: QueryResult[] = []

  for (const query of corpus.queries) {
    const hits = await engine.search(query)

    results.push({ id: query.id, category: query.category, rank: firstRelevantRank(hits, query.gold) })
  }

  return { engine: engine.name, results, metrics: metricsByCategory(results) }
}

export type ReportMeta = {
  date: string
  sha: string
  corpusSha256: string
  queryCount: number
  meetingCount: number
  replayAvailable: boolean
  notes: string[]
}

const pct = (value: number) => value.toFixed(2)

export function renderReport(reports: EngineReport[], meta: ReportMeta): string {
  const lines: string[] = []

  lines.push(meta.replayAvailable ? "# M6 search eval — SYNTHETIC" : "# M6 search eval — SYNTHETIC — replay pending")
  lines.push("")
  lines.push("Generated by `npm run search:eval` (docs/parity/m6.md, B8). Synthetic corpus; no transcript or query text here.")
  lines.push("")
  lines.push(`- Date: ${meta.date}`)
  lines.push(`- Commit: ${meta.sha}`)
  lines.push(`- Corpus: \`tests/fixtures/search/corpus.he.json\` sha256 \`${meta.corpusSha256}\``)
  lines.push(`- Size: ${meta.meetingCount} meetings, ${meta.queryCount} queries`)
  lines.push(`- Engines: ${reports.map((report) => report.engine).join(", ")}`)
  for (const note of meta.notes) lines.push(`- ${note}`)
  lines.push("")
  lines.push("Metrics are recall@1 / recall@5 / recall@10 / MRR@10. A hit is relevant when it is a chunk of the gold meeting touching a gold segment.")
  lines.push("")

  const categories = [...EVAL_CATEGORIES.filter((category) => reports.some((report) => report.metrics[category])), "overall"]

  lines.push(`| category | n | ${reports.map((report) => report.engine).join(" | ")} |`)
  lines.push(`|---|---|${reports.map(() => "---").join("|")}|`)
  for (const category of categories) {
    const n = reports[0]?.metrics[category]?.n ?? 0
    const cells = reports.map((report) => {
      const metric = report.metrics[category]

      return metric ? `${pct(metric.recall1)} / ${pct(metric.recall5)} / ${pct(metric.recall10)} / ${pct(metric.mrr10)}` : "—"
    })

    lines.push(`| ${category} | ${n} | ${cells.join(" | ")} |`)
  }
  lines.push("")

  return `${lines.join("\n")}\n`
}
