/**
 * Pure helpers behind `npm run db:schema:generate` / `db:schema:check`
 * (docs/parity/m10.md, "Schema (D)"). `db/schema.sql` is a normalized
 * `pg_dump --schema-only` of a database with every migration applied, so the
 * file is reproducible: the same migrations on the same server major version
 * give byte-identical output.
 */

export const SCHEMA_DUMP_ARGS = [
  "--schema-only",
  "--no-owner",
  "--no-privileges",
  "--no-comments",
  "--no-tablespaces",
] as const

export function schemaHeader(firstVersion: string, lastVersion: string): string {
  return [
    `-- GENERATED by npm run db:schema:generate from db/migrations (${firstVersion}–${lastVersion}). Do not edit.`,
    "-- Source of truth: db/migrations/*.sql. CI (`schema` job) diffs this file against a fresh pg_dump",
    "-- of pgvector/pgvector:0.8.1-pg17 with every migration applied.",
  ].join("\n")
}

const DROP_LINE_PATTERNS: RegExp[] = [
  // PG 17.6+ / 16.10+ emit a random restrict key around the dump.
  /^\\(un)?restrict\b/,
  /^SET\s/,
  /^SELECT pg_catalog\.set_config\(/,
  /^-- Dumped (from|by)\b/,
  /^-- (PostgreSQL database dump|PostgreSQL database dump complete)\s*$/,
]

/**
 * Normalizes raw pg_dump output: LF line endings, no session `SET` lines, no
 * restrict keys or version headers, no trailing whitespace, single blank lines
 * between blocks, the generated header on top and exactly one trailing newline.
 */
export function normalizeSchemaDump(raw: string, header: string): string {
  const lines = raw.replace(/\r\n?/g, "\n").split("\n")
  const kept: string[] = []

  for (const line of lines) {
    const trimmedEnd = line.replace(/\s+$/, "")

    if (DROP_LINE_PATTERNS.some((pattern) => pattern.test(trimmedEnd))) continue
    kept.push(trimmedEnd)
  }

  // The dropped banner leaves "--" lines framing nothing. Object headers are
  // always "--", "-- Name: …", "--", so a run of 2+ bare "--" lines is debris.
  const withoutEmptyBanners = kept.filter(
    (line, index) => line !== "--" || (kept[index - 1] !== "--" && kept[index + 1] !== "--")
  )

  const collapsed: string[] = []

  for (const line of withoutEmptyBanners) {
    if (line === "" && (collapsed.length === 0 || collapsed[collapsed.length - 1] === "")) continue
    collapsed.push(line)
  }

  while (collapsed.length > 0 && collapsed[collapsed.length - 1] === "") collapsed.pop()

  return `${header}\n\n${collapsed.join("\n")}\n`
}

/** First and last migration versions from file names like `001_init.sql`. */
export function migrationRange(fileNames: string[]): { first: string; last: string } {
  const versions = fileNames
    .map((name) => name.match(/^(\d{3,})_[\w-]+\.sql$/)?.[1])
    .filter((version): version is string => Boolean(version))
    .sort()

  if (versions.length === 0) throw new Error("no migration files")

  return { first: versions[0], last: versions[versions.length - 1] }
}

type Edit = { kind: " " | "-" | "+"; line: string }

function diffLines(a: string[], b: string[]): Edit[] {
  const n = a.length
  const m = b.length
  // LCS table over suffixes; schema files are a few thousand lines.
  const width = m + 1
  const table = new Uint32Array((n + 1) * width)

  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      table[i * width + j] =
        a[i] === b[j] ? table[(i + 1) * width + j + 1] + 1 : Math.max(table[(i + 1) * width + j], table[i * width + j + 1])
    }
  }

  const edits: Edit[] = []
  let i = 0
  let j = 0

  while (i < n && j < m) {
    if (a[i] === b[j]) {
      edits.push({ kind: " ", line: a[i] })
      i += 1
      j += 1
    } else if (table[(i + 1) * width + j] >= table[i * width + j + 1]) {
      edits.push({ kind: "-", line: a[i] })
      i += 1
    } else {
      edits.push({ kind: "+", line: b[j] })
      j += 1
    }
  }
  while (i < n) edits.push({ kind: "-", line: a[i++] })
  while (j < m) edits.push({ kind: "+", line: b[j++] })

  return edits
}

/**
 * Unified diff (3 lines of context) from `expected` (the committed file) to
 * `actual` (the fresh dump). Empty string when they are equal.
 */
export function unifiedDiff(expected: string, actual: string, labels = { from: "db/schema.sql", to: "fresh pg_dump" }): string {
  if (expected === actual) return ""

  const a = expected.replace(/\r\n?/g, "\n").split("\n")
  const b = actual.replace(/\r\n?/g, "\n").split("\n")
  const edits = diffLines(a, b)
  const context = 3
  const out: string[] = [`--- ${labels.from}`, `+++ ${labels.to}`]
  // Positions (1-based) in a and b for every edit.
  const positions: Array<{ aLine: number; bLine: number }> = []
  let aLine = 1
  let bLine = 1

  for (const edit of edits) {
    positions.push({ aLine, bLine })
    if (edit.kind !== "+") aLine += 1
    if (edit.kind !== "-") bLine += 1
  }

  let index = 0

  while (index < edits.length) {
    if (edits[index].kind === " ") {
      index += 1
      continue
    }

    const start = Math.max(0, index - context)
    let end = index

    // Extend the hunk while changes are within 2*context of each other.
    while (end < edits.length) {
      if (edits[end].kind !== " ") {
        end += 1
        continue
      }
      let lookahead = end

      while (lookahead < edits.length && edits[lookahead].kind === " " && lookahead - end < context * 2) lookahead += 1
      if (lookahead < edits.length && edits[lookahead].kind !== " ") {
        end = lookahead
      } else {
        end = Math.min(edits.length, end + context)
        break
      }
    }

    const hunk = edits.slice(start, end)
    const aCount = hunk.filter((edit) => edit.kind !== "+").length
    const bCount = hunk.filter((edit) => edit.kind !== "-").length

    out.push(`@@ -${positions[start].aLine},${aCount} +${positions[start].bLine},${bCount} @@`)
    for (const edit of hunk) out.push(`${edit.kind}${edit.line}`)
    index = end
  }

  return `${out.join("\n")}\n`
}
