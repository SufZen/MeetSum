export type TasksMessages = typeof tasksMessagesEn

/** Task strings for a locale (Hebrew for `he`, English otherwise). */
export function getTasksMessages(locale: string | undefined): TasksMessages {
  return locale === "he" ? tasksMessagesHe : tasksMessagesEn
}

export function formatTaskMessage(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match
  )
}
