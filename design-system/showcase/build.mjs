// Generates showcase/tokens.generated.css from ../tokens.css so the showcase
// always renders the exact production tokens. The showcase follows the viewer
// theme (prefers-color-scheme) and an explicit [data-theme] toggle, so the
// production `.dark` block is emitted under both selectors.
//
//   node design-system/showcase/build.mjs            -> writes generated css
//   node design-system/showcase/build.mjs --preview  -> also copies a doctype-
//                                                      wrapped preview to public/ds/
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(join(here, "..", "tokens.css"), "utf8")

function block(selector) {
  const start = src.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`missing ${selector}`)
  let depth = 0
  for (let i = src.indexOf("{", start); i < src.length; i++) {
    if (src[i] === "{") depth++
    if (src[i] === "}" && --depth === 0) return src.slice(src.indexOf("{", start) + 1, i)
  }
  throw new Error(`unclosed ${selector}`)
}

const light = block(":root")
const dark = block(".dark")
const hebrew = block(":lang(he)")
const reduced = block("@media (prefers-reduced-motion: reduce)")
const keyframesStart = src.indexOf("/* ---- Keyframes")
const keyframesEnd = src.indexOf("/* Breakpoints")
const keyframes = src.slice(keyframesStart, keyframesEnd > 0 ? keyframesEnd : undefined)

const out = `/* GENERATED by build.mjs from design-system/tokens.css — do not edit. */
:root {${light}}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {${dark}  color-scheme: dark;
  }
}
:root[data-theme="dark"] {${dark}  color-scheme: dark;
}
:lang(he) {${hebrew}}
@media (prefers-reduced-motion: reduce) {${reduced}}
${keyframes}`

writeFileSync(join(here, "tokens.generated.css"), out)
console.log("wrote tokens.generated.css", out.length, "bytes")

if (process.argv.includes("--preview")) {
  const pub = join(here, "..", "..", "public", "ds")
  mkdirSync(pub, { recursive: true })
  const html = readFileSync(join(here, "index.html"), "utf8")
  writeFileSync(
    join(pub, "index.html"),
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"></head><body>\n${html}\n</body></html>`
  )
  for (const f of ["tokens.generated.css", "cadence.css", "cadence.js"]) copyFileSync(join(here, f), join(pub, f))
  console.log("preview -> public/ds/index.html")
}
