/**
 * M10 B6 (docs/parity/m10.md, "Runbooks"): every environment variable the
 * code reads is documented in `.env.example` (allowlist: NODE_ENV,
 * NEXT_RUNTIME, CI, npm_*, E2E_*, PORT, HOSTNAME, VITEST), and the generated
 * docs/env-matrix.md is current.
 */
import { readFileSync } from "node:fs"
import path from "node:path"

import { describe, expect, it } from "vitest"

import {
  buildEnvMatrix,
  collectEnvUsage,
  consumerOf,
  isAllowlisted,
  isSecretName,
  parseEnvExample,
  scanEnvReads,
  undocumentedReads,
} from "@/scripts/env-matrix"

const root = path.resolve(__dirname, "..")

/** Reads still missing from `.env.example` (sorted). Empty since the M10 integration step. */
const PENDING_ENV_EXAMPLE: string[] = []

describe("env documentation", () => {
  it("parses .env.example sections, defaults, commented entries and notes", () => {
    const entries = parseEnvExample(
      [
        "# --- Hardening and observability (M10) ---------",
        "# Server log level.",
        "# LOG_LEVEL=",
        "MEETSUM_WORKER_HEALTH_PORT=3101",
        "",
        "# --- docker compose infrastructure ---",
        "POSTGRES_DB=meetings",
      ].join("\n")
    )

    expect(entries).toEqual([
      { name: "LOG_LEVEL", section: "Hardening and observability (M10)", milestone: "M10", defaultValue: "", commented: true, notes: "Server log level." },
      { name: "MEETSUM_WORKER_HEALTH_PORT", section: "Hardening and observability (M10)", milestone: "M10", defaultValue: "3101", commented: false, notes: "" },
      { name: "POSTGRES_DB", section: "docker compose infrastructure", milestone: "", defaultValue: "meetings", commented: false, notes: "" },
    ])
  })

  it("scans process.env reads and classifies consumers", () => {
    expect(
      scanEnvReads('const a = process.env.REDIS_URL; const b = process.env["LOG_LEVEL"]; env.S3_BUCKET; envText(env, "GROQ_KEY"); other.NOT_THIS')
    ).toEqual(["REDIS_URL", "LOG_LEVEL", "S3_BUCKET", "GROQ_KEY"])
    expect(consumerOf("worker/index.ts")).toBe("worker")
    expect(consumerOf("scripts/migrate.ts")).toBe("migrate")
    expect(consumerOf("mcp/server.mjs")).toBe("mcp")
    expect(consumerOf("scripts/m9-e2e-seed.ts")).toBe("e2e")
    expect(consumerOf("app/api/health/route.ts")).toBe("app")
    expect(isAllowlisted("npm_package_version")).toBe(true)
    expect(isAllowlisted("E2E_BASE_URL")).toBe(true)
    expect(isSecretName("SENTRY_DSN")).toBe(true)
    expect(isSecretName("MEETSUM_SESSION_SECRET")).toBe(true)
    expect(isSecretName("REDIS_URL")).toBe(false)
  })

  it("every variable the code reads is in .env.example", () => {
    const entries = parseEnvExample(readFileSync(path.join(root, ".env.example"), "utf8"))
    const usage = collectEnvUsage(root)

    expect(usage.size).toBeGreaterThan(50)
    // Read by code but missing from .env.example before M10. `.env.example`
    // is frozen to the orchestrator, so these wait for it (M10 B report);
    // any NEW undocumented read fails here, and so does a stale entry below.
    expect(undocumentedReads(usage, entries)).toEqual(PENDING_ENV_EXAMPLE)
  })

  it("docs/env-matrix.md is generated and current (npm run env:matrix)", () => {
    const current = readFileSync(path.join(root, "docs/env-matrix.md"), "utf8").replace(/\r\n/g, "\n")

    expect(current).toBe(buildEnvMatrix(root))
    expect(current).toContain("GENERATED by `npm run env:matrix`")
    // Secret example values are never copied into the doc.
    expect(current).not.toMatch(/MEETSUM_SESSION_SECRET` \|[^|]*\|[^|]*\| `[^`(]/)
  })
})
