/**
 * M9 RTL screenshot matrix and axe run (docs/parity/m9.md, Acceptance 17.13
 * and 18; Package C4). `npm run screenshots` after `npm run m9:e2e-seed`.
 *
 * Surfaces × he/en × light/dark at 1440×900, plus 390×844 for inbox, meeting
 * and share. Output goes to the gitignored
 * `test-results/m9-screenshots/<surface>/<locale>-<theme>-<w>.png`, with
 * `index.md` and `a11y-report.json`; nothing here is committed (user
 * decision, 2026-10-13). Serious/critical axe violations fail the run unless
 * listed in `scripts/axe-allowlist.json` with a reason.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

import AxeBuilder from "@axe-core/playwright"
import { expect, test, type Page } from "@playwright/test"

import { assertLocalBaseUrl, env, signIn, type M9Principal } from "./m9-env"

const OUT = path.join("test-results", "m9-screenshots")
const LOCALES = ["he", "en"] as const
const THEMES = ["light", "dark"] as const
const DESKTOP = { width: 1440, height: 900 }
const MOBILE = { width: 390, height: 844 }

type Surface = {
  id: string
  who: M9Principal | null
  path: (locale: string) => string
  mobile?: boolean
  /** Waits for the surface to be ready before the capture. */
  ready?: (page: Page) => Promise<void>
}

const meeting = env.E2E_M9_HEBREW_MEETING_ID ?? ""

const SURFACES: Surface[] = [
  { id: "login", who: null, path: (l) => `/${l}/login` },
  { id: "inbox-summary", who: "owner", path: (l) => `/${l}?meeting=${meeting}`, mobile: true },
  { id: "transcript", who: "owner", path: (l) => `/${l}?meeting=${meeting}&tab=transcript` },
  { id: "ask", who: "owner", path: (l) => `/${l}?meeting=${meeting}&tab=ask` },
  { id: "meeting", who: "owner", path: (l) => `/${l}?meeting=${meeting}`, mobile: true },
  { id: "tasks", who: "owner", path: (l) => `/${l}/tasks` },
  { id: "analytics", who: "admin", path: (l) => `/${l}/analytics` },
  {
    id: "notifications",
    who: "admin",
    path: (l) => `/${l}`,
    ready: async (page) => {
      await page.getByTestId("notification-bell").click()
      await expect(page.locator("[data-slot=popover-content]")).toBeVisible()
    },
  },
  { id: "onboarding", who: "fresh", path: (l) => `/${l}/onboarding` },
  { id: "settings", who: "owner", path: (l) => `/${l}?panel=settings` },
  { id: "admin", who: "owner", path: (l) => `/${l}?panel=admin` },
  { id: "share", who: null, path: () => `/share/${env.E2E_M9_SHARE_TOKEN ?? "missing"}`, mobile: true },
  { id: "share-password", who: null, path: () => `/share/${env.E2E_M9_PROTECTED_SHARE_TOKEN ?? "missing"}` },
  { id: "404", who: "owner", path: (l) => `/${l}/this-page-does-not-exist` },
  { id: "error", who: "owner", path: (l) => `/${l}?__error=1` },
  { id: "offline", who: null, path: () => "/offline.html" },
]

type AxeFinding = { surface: string; locale: string; theme: string; width: number; rule: string; impact: string; nodes: number }

function loadAllowlist(): Array<{ surface: string; rule: string; reason: string }> {
  try {
    const parsed = JSON.parse(readFileSync("scripts/axe-allowlist.json", "utf8")) as {
      entries?: Array<{ surface: string; rule: string; reason: string }>
    }

    return (parsed.entries ?? []).filter((entry) => entry.reason?.trim())
  } catch {
    return []
  }
}

const findings: AxeFinding[] = []
const shots: string[] = []

test.describe.configure({ mode: "serial" })

test.beforeAll(() => {
  assertLocalBaseUrl()
  mkdirSync(OUT, { recursive: true })
})

test.afterAll(() => {
  writeFileSync(path.join(OUT, "a11y-report.json"), `${JSON.stringify({ generatedAt: new Date().toISOString(), findings }, null, 2)}\n`)
  writeFileSync(
    path.join(OUT, "index.md"),
    [
      "# M9 screenshot matrix",
      "",
      "Generated by `npm run screenshots` (not committed).",
      "",
      ...shots.map((file) => `- [${file}](${file.replaceAll("\\", "/")})`),
      "",
    ].join("\n")
  )
})

for (const surface of SURFACES) {
  for (const locale of LOCALES) {
    for (const theme of THEMES) {
      test(`${surface.id} ${locale} ${theme}`, async ({ browser }) => {
        const viewports = surface.mobile ? [DESKTOP, MOBILE] : [DESKTOP]

        for (const viewport of viewports) {
          const context = await browser.newContext({
            viewport,
            colorScheme: theme,
            locale: locale === "he" ? "he-IL" : "en-US",
            extraHTTPHeaders: { "accept-language": locale === "he" ? "he-IL,he" : "en-US,en" },
            // Screenshots need no service worker; blocking it rules out a
            // registration reload mid-capture (the registrar itself no longer
            // reloads on the first claim, M9 follow-up item 7).
            serviceWorkers: "block",
          })

          await context.addInitScript((value) => {
            try {
              window.localStorage.setItem("theme", value)
            } catch {
              // Storage blocked: the color-scheme emulation still applies.
            }
          }, theme)

          if (surface.who) await signIn(context, surface.who, locale)
          else await context.addCookies([{ name: "meetsum_locale", value: locale, url: process.env.E2E_BASE_URL || "http://localhost:3000" }])

          const page = await context.newPage()

          await page.goto(surface.path(locale))
          await page.waitForLoadState("load")
          try {
            await surface.ready?.(page)
          } catch (error) {
            // One retry after a late navigation (redirect or reload) replaced the page.
            await page.waitForLoadState("load")
            if (!surface.ready) throw error
            await surface.ready(page)
          }

          const dir = path.join(OUT, surface.id)
          const file = path.join(dir, `${locale}-${theme}-${viewport.width}.png`)

          mkdirSync(dir, { recursive: true })
          await page.screenshot({ path: file, fullPage: true })
          shots.push(path.relative(OUT, file))

          const results = await new AxeBuilder({ page }).analyze()
          const allow = loadAllowlist()

          for (const violation of results.violations) {
            if (violation.impact !== "serious" && violation.impact !== "critical") continue
            if (allow.some((entry) => entry.rule === violation.id && (entry.surface === surface.id || entry.surface === "*"))) continue
            findings.push({
              surface: surface.id,
              locale,
              theme,
              width: viewport.width,
              rule: violation.id,
              impact: violation.impact,
              nodes: violation.nodes.length,
            })
          }

          await context.close()
        }

        expect(
          findings.filter((finding) => finding.surface === surface.id && finding.locale === locale && finding.theme === theme),
          "serious/critical axe violations (see a11y-report.json)"
        ).toEqual([])
      })
    }
  }
}
