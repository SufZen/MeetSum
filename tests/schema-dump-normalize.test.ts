import { describe, expect, it } from "vitest"

import { migrationRange, normalizeSchemaDump, SCHEMA_DUMP_ARGS, schemaHeader, unifiedDiff } from "@/lib/db/schema-dump"

const RAW = [
  "--",
  "-- PostgreSQL database dump",
  "--",
  "",
  "\\restrict 4XkQ0q2PZ8d1Yp",
  "",
  "-- Dumped from database version 17.6 (Debian 17.6-1.pgdg120+1)",
  "-- Dumped by pg_dump version 17.6 (Debian 17.6-1.pgdg120+1)",
  "",
  "SET statement_timeout = 0;",
  "SET client_encoding = 'UTF8';",
  "SELECT pg_catalog.set_config('search_path', '', false);",
  "SET check_function_bodies = false;",
  "",
  "--",
  "-- Name: pg_trgm; Type: EXTENSION; Schema: -; Owner: -",
  "--",
  "",
  "CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;",
  "",
  "",
  "",
  "SET default_tablespace = '';",
  "",
  "SET default_table_access_method = heap;",
  "",
  "--",
  "-- Name: users; Type: TABLE; Schema: public; Owner: -",
  "--",
  "",
  "CREATE TABLE public.users (   ",
  "    id text NOT NULL",
  ");",
  "",
  "",
  "--",
  "-- PostgreSQL database dump complete",
  "--",
  "",
  "\\unrestrict 4XkQ0q2PZ8d1Yp",
  "",
].join("\r\n")

describe("normalizeSchemaDump", () => {
  const header = schemaHeader("001", "032")
  const out = normalizeSchemaDump(RAW, header)

  it("starts with the generated header and ends with one newline", () => {
    expect(out.startsWith("-- GENERATED by npm run db:schema:generate from db/migrations (001–032). Do not edit.\n")).toBe(true)
    expect(out.endsWith(");\n")).toBe(true)
  })

  it("drops restrict keys, SET lines, set_config, version headers and the banners", () => {
    expect(out).not.toMatch(/restrict/)
    expect(out).not.toMatch(/^SET /m)
    expect(out).not.toContain("set_config")
    expect(out).not.toContain("Dumped")
    expect(out).not.toContain("PostgreSQL database dump")
    expect(out).not.toMatch(/^--\n--$/m)
  })

  it("keeps object headers and DDL, LF only, no trailing spaces, no double blank lines", () => {
    expect(out).toContain("--\n-- Name: users; Type: TABLE; Schema: public; Owner: -\n--\n\nCREATE TABLE public.users (\n")
    expect(out).toContain("CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;")
    expect(out).not.toContain("\r")
    expect(out).not.toMatch(/[ \t]+$/m)
    expect(out).not.toMatch(/\n\n\n/)
  })

  it("is idempotent on its own body and independent of the restrict key", () => {
    const other = normalizeSchemaDump(RAW.replace(/4XkQ0q2PZ8d1Yp/g, "zzzzzzzz"), header)

    expect(other).toBe(out)
  })
})

describe("schema dump helpers", () => {
  it("dumps schema only, without owners, grants, comments or tablespaces", () => {
    expect([...SCHEMA_DUMP_ARGS]).toEqual(["--schema-only", "--no-owner", "--no-privileges", "--no-comments", "--no-tablespaces"])
  })

  it("derives the migration range from file names", () => {
    expect(migrationRange(["002_b.sql", "001_a.sql", "README.md", "032_drop_x.sql"])).toEqual({ first: "001", last: "032" })
    expect(() => migrationRange(["notes.txt"])).toThrow()
  })

  it("prints a unified diff only when the texts differ", () => {
    expect(unifiedDiff("a\nb\nc\n", "a\nb\nc\n")).toBe("")
    const diff = unifiedDiff("a\nb\nc\nd\n", "a\nB\nc\nd\n")

    expect(diff).toContain("--- db/schema.sql")
    expect(diff).toContain("+++ fresh pg_dump")
    expect(diff).toContain("@@ -1,5 +1,5 @@")
    expect(diff).toContain("-b\n+B")
  })
})
